import {
  FINDING_KIND_LABELS,
  normaliseName,
  resolveProposalActors,
  validateProcess,
  type Actor,
  type FindingKind,
} from '@productflow/domain';
import { ReactFlowProvider } from '@xyflow/react';
import { Sparkles } from 'lucide-react';
import { useMemo, useState } from 'react';
import { Alert, Badge, Button, Dialog } from '../../components/ui';
import { errorMessage } from '../../lib/errors';
import type { AnalysisResponse } from '../../lib/api';
import { ProcessCanvas } from './ProcessCanvas';

const noop = () => undefined;

export function ProposalDialog({
  response,
  existingActors,
  replacesExistingMap,
  onAccept,
  onDiscard,
}: {
  response: AnalysisResponse;
  existingActors: Actor[];
  replacesExistingMap: boolean;
  onAccept: () => Promise<void>;
  onDiscard: () => void;
}) {
  const { proposal } = response;
  const [accepting, setAccepting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Preview with name-based pseudo actors; real ids are resolved on accept.
  const previewActors = useMemo<Actor[]>(
    () => proposal.actors.map((a) => ({ id: a.name, name: a.name, kind: a.kind })),
    [proposal],
  );
  const previewGraph = useMemo(() => resolveProposalActors(proposal, previewActors), [proposal, previewActors]);
  const issues = useMemo(
    () => validateProcess({ ...previewGraph, actors: previewActors, findings: proposal.findings }),
    [previewGraph, previewActors, proposal.findings],
  );
  const existing = new Set(existingActors.map((a) => normaliseName(a.name)));
  const newActors = proposal.actors.filter((a) => !existing.has(normaliseName(a.name)));
  const inferredCount = proposal.nodes.filter((n) => n.origin === 'inferred').length;
  const counts = proposal.findings.reduce<Partial<Record<FindingKind, number>>>(
    (acc, f) => ({ ...acc, [f.kind]: (acc[f.kind] ?? 0) + 1 }),
    {},
  );
  const errors = issues.filter((i) => i.severity === 'error').length;
  const warnings = issues.length - errors;

  return (
    <Dialog
      open
      onClose={accepting ? noop : onDiscard}
      size="xl"
      title="Review the generated process map"
      description={<>Generated by {response.model}. Nothing is saved until you accept it into the draft and save.</>}
      footer={
        <>
          <Button onClick={onDiscard} disabled={accepting}>
            Discard
          </Button>
          <Button
            variant="primary"
            loading={accepting}
            onClick={async () => {
              setAccepting(true);
              setError(null);
              try {
                await onAccept();
              } catch (err) {
                setError(errorMessage(err));
                setAccepting(false);
              }
            }}
          >
            {replacesExistingMap ? 'Replace current map' : 'Accept into draft'}
          </Button>
        </>
      }
    >
      <div className="grid gap-4 lg:grid-cols-[1fr_320px]">
        <div className="h-[55vh] min-h-80 overflow-hidden rounded-md border border-slate-200 bg-slate-50">
          <ReactFlowProvider>
            <ProcessCanvas
              graph={previewGraph}
              actors={previewActors}
              issues={issues}
              selection={null}
              readOnly
              dispatch={noop}
              fitSignal={0}
            />
          </ReactFlowProvider>
        </div>
        <div className="space-y-4 text-sm">
          {error ? <Alert tone="error">{error}</Alert> : null}
          {replacesExistingMap ? (
            <Alert tone="warning" title="This replaces the current draft map">
              Your unsaved and saved draft map is replaced. Findings you wrote or already reviewed are kept. You can undo this
              before saving.
            </Alert>
          ) : null}
          <section>
            <h3 className="font-semibold text-slate-900">{proposal.processName}</h3>
            <p className="mt-1 text-slate-600">{proposal.summary}</p>
          </section>
          <dl className="grid grid-cols-2 gap-2 text-xs">
            <Stat label="Steps" value={proposal.nodes.length} />
            <Stat label="Connections" value={proposal.edges.length} />
            <Stat label="Actors" value={proposal.actors.length} />
            <Stat
              label="Validation"
              value={
                errors
                  ? `${errors} error${errors > 1 ? 's' : ''}`
                  : warnings
                    ? `${warnings} warning${warnings > 1 ? 's' : ''}`
                    : 'Clean'
              }
            />
          </dl>
          {inferredCount > 0 ? (
            <p className="flex gap-1.5 text-xs text-violet-800">
              <Sparkles className="mt-px size-3.5 shrink-0" />
              {inferredCount} step{inferredCount > 1 ? 's were' : ' was'} inferred rather than stated in the description. They are
              marked on the map; check them before approval.
            </p>
          ) : null}
          {proposal.findings.length > 0 ? (
            <section>
              <h4 className="mb-1.5 text-xs font-semibold tracking-wide text-slate-500 uppercase">Findings (draft)</h4>
              <div className="flex flex-wrap gap-1.5">
                {(Object.entries(counts) as [FindingKind, number][]).map(([kind, n]) => (
                  <Badge key={kind} tone={kind === 'missing_information' ? 'amber' : 'blue'}>
                    {n} {FINDING_KIND_LABELS[kind].toLowerCase()}
                  </Badge>
                ))}
              </div>
              <ul className="mt-2 max-h-40 space-y-1 overflow-y-auto text-xs text-slate-600">
                {proposal.findings
                  .filter((f) => f.kind === 'missing_information' || f.kind === 'ambiguity')
                  .map((f) => (
                    <li key={f.elementKey} className="rounded bg-amber-50 px-2 py-1 text-amber-900">
                      {f.statement}
                    </li>
                  ))}
              </ul>
            </section>
          ) : null}
          {newActors.length > 0 ? (
            <p className="text-xs text-slate-500">
              Accepting adds {newActors.length} new actor{newActors.length > 1 ? 's' : ''} to the project:{' '}
              {newActors.map((a) => a.name).join(', ')}.
            </p>
          ) : null}
        </div>
      </div>
    </Dialog>
  );
}

function Stat({ label, value }: { label: string; value: number | string }) {
  return (
    <div className="rounded-md border border-slate-200 bg-slate-50 px-2.5 py-2">
      <dt className="text-slate-500">{label}</dt>
      <dd className="text-sm font-semibold text-slate-900">{value}</dd>
    </div>
  );
}
